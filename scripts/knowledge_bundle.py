"""Clinical knowledge bundle: export the database to the repo, or verify it against the bundle.

    uv run python scripts/knowledge_bundle.py export --version 1.0.0
        Writes knowledge/bundle/*.jsonl and manifest.json from the database, and regenerates
        src/medicalbooking/modules/clinical/domain/knowledge_bundle.py with the digest.

    uv run python scripts/knowledge_bundle.py verify
        Reads the database and the bundle, prints the digest and row counts, and says OK or
        DRIFT. Writes nothing. Exit code 0 means OK, 1 means DRIFT or a failure.

Only counts and digests are printed, never row contents or connection strings.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from medicalbooking.config import Settings
from medicalbooking.modules.clinical.domain.knowledge_digest import TABLES, knowledge_digest
from medicalbooking.modules.clinical.infrastructure.knowledge_bundle_files import (
    BundleError,
    read_bundle,
    write_bundle,
)
from medicalbooking.modules.clinical.infrastructure.knowledge_snapshot import (
    read_knowledge_tables,
)
from medicalbooking.shared.infrastructure.database import create_database_engine

REPO_ROOT = Path(__file__).resolve().parents[1]
BUNDLE_DIR = REPO_ROOT / "knowledge" / "bundle"
DOMAIN_CONSTANTS = (
    REPO_ROOT / "src" / "medicalbooking" / "modules" / "clinical" / "domain" / "knowledge_bundle.py"
)

_CONSTANTS_TEMPLATE = '''"""The knowledge bundle this application was built with.

GENERATED by ``scripts/knowledge_bundle.py export``. Do not edit by hand: the export writes the
digest of the files in knowledge/bundle/, and a test checks that they still match.
"""

BUNDLE_VERSION = "{version}"
BUNDLE_DIGEST = "{digest}"
'''


def _engine():
    return create_database_engine(Settings())


def export(version: str) -> int:
    engine = _engine()
    try:
        tables = read_knowledge_tables(engine)
    finally:
        engine.dispose()
    manifest = write_bundle(BUNDLE_DIR, tables, version)
    DOMAIN_CONSTANTS.write_text(
        _CONSTANTS_TEMPLATE.format(version=version, digest=manifest["digest"]),
        encoding="utf-8",
    )
    print(f"bundle_version={version}")
    print(f"digest={manifest['digest']}")
    for spec in TABLES:
        print(f"{spec.name}={manifest['files'][spec.name]['rows']}")
    return 0


def verify() -> int:
    try:
        bundle_version, bundle_digest, _ = read_bundle(BUNDLE_DIR)
    except BundleError as error:
        print(f"bundle: {error}")
        print("DRIFT")
        return 1
    engine = _engine()
    try:
        tables = read_knowledge_tables(engine)
    finally:
        engine.dispose()
    result = knowledge_digest(tables)
    print(f"bundle_version={bundle_version}")
    print(f"bundle_digest={bundle_digest}")
    print(f"database_digest={result.digest}")
    for spec in TABLES:
        print(f"{spec.name}={result.counts[spec.name]}")
    if result.digest == bundle_digest:
        print("OK")
        return 0
    print("DRIFT")
    return 1


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    commands = parser.add_subparsers(dest="command", required=True)
    export_cmd = commands.add_parser("export", help="write the bundle from the database")
    export_cmd.add_argument("--version", required=True, help="bundle version, for example 1.0.0")
    commands.add_parser("verify", help="compare the database with the bundle; writes nothing")
    args = parser.parse_args(argv)
    try:
        if args.command == "export":
            return export(args.version)
        return verify()
    except Exception as error:
        # Database and driver errors may carry connection data: report the type only.
        print(f"knowledge bundle {args.command} failed: {type(error).__name__}")
        return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
